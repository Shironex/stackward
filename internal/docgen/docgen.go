// Package docgen renders the embedded check catalog as Markdown pages:
// one page per check plus an index. The pages are committed under
// docs/checks and a test fails when they drift from the catalog, so adding
// or editing a catalog entry means running `go run ./cmd/docgen` once.
package docgen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/Shironex/stackward/internal/catalog"
)

// Banner is the first line of every generated page.
const Banner = "<!-- Generated by `go run ./cmd/docgen` from the check catalog. Do not edit by hand. -->"

// Render returns every generated page keyed by file name (for example
// "SYS-001.md" and "index.md"), in memory and without touching the disk.
func Render(cat *catalog.Catalog) map[string][]byte {
	pages := map[string][]byte{}
	entries := cat.Entries()
	for _, e := range entries {
		pages[e.ID+".md"] = []byte(page(e))
	}
	pages["index.md"] = []byte(index(entries))
	return pages
}

// Write renders the catalog into dir, creating it if needed and removing
// check pages that no longer have a catalog entry.
func Write(cat *catalog.Catalog, dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // public documentation directory
		return err
	}
	pages := Render(cat)
	for name, body := range pages {
		if err := os.WriteFile(filepath.Join(dir, name), body, 0o644); err != nil { //nolint:gosec // public documentation files
			return err
		}
	}
	stale, err := staleFiles(dir, pages)
	if err != nil {
		return err
	}
	for _, name := range stale {
		if err := os.Remove(filepath.Join(dir, name)); err != nil {
			return err
		}
	}
	return nil
}

// Check compares dir with a fresh render and returns one line per problem:
// a missing page, a page whose text differs, or a page with no catalog
// entry. An empty result means the committed pages are current.
func Check(cat *catalog.Catalog, dir string) ([]string, error) {
	pages := Render(cat)
	var problems []string
	names := make([]string, 0, len(pages))
	for n := range pages {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, name := range names {
		got, err := os.ReadFile(filepath.Join(dir, name))
		switch {
		case os.IsNotExist(err):
			problems = append(problems, name+": missing")
		case err != nil:
			return nil, err
		case !bytes.Equal(got, pages[name]):
			problems = append(problems, name+": out of date")
		}
	}
	stale, err := staleFiles(dir, pages)
	if err != nil {
		return nil, err
	}
	for _, name := range stale {
		problems = append(problems, name+": no catalog entry")
	}
	return problems, nil
}

// staleFiles lists Markdown files in dir that Render does not produce.
func staleFiles(dir string, pages map[string][]byte) ([]string, error) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var stale []string
	for _, de := range ents {
		name := de.Name()
		if _, ok := pages[name]; !ok && strings.HasSuffix(name, ".md") {
			stale = append(stale, name)
		}
	}
	return stale, nil
}

func page(e catalog.Entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n\n# %s: %s\n\n", Banner, e.ID, e.Title)
	fmt.Fprintf(&b, "- **Group:** %s\n", catalog.GroupName(e.Group))
	fmt.Fprintf(&b, "- **Severity when it fails:** %s\n", e.Severity)
	if e.NeedsRoot {
		b.WriteString("- **Root:** the full result needs `sudo`. Without root this check reports `unknown`, never a pass.\n")
	} else {
		b.WriteString("- **Root:** not needed\n")
	}
	b.WriteString("\n")
	prose(&b, "Why it matters", e.Rationale)
	if e.Verify != "" {
		fmt.Fprintf(&b, "## Verify by hand\n\n```sh\n%s\n```\n\n", strings.TrimSpace(e.Verify))
	}
	prose(&b, "How to fix it", e.Fix)
	prose(&b, "What a fix can break", e.Breaks)
	if e.Docs != "" {
		fmt.Fprintf(&b, "## More\n\n<%s>\n\n", strings.TrimSpace(e.Docs))
	}
	fmt.Fprintf(&b, "Run `stackward explain %s` for the same text in your terminal. [All checks](index.md).\n", e.ID)
	return b.String()
}

func prose(b *strings.Builder, title, body string) {
	if strings.TrimSpace(body) == "" {
		return
	}
	fmt.Fprintf(b, "## %s\n\n%s\n\n", title, strings.TrimSpace(body))
}

func index(entries []catalog.Entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n\n# Checks\n\n", Banner)
	b.WriteString("Every check has a stable id that is never reused. Severity is how bad a failure is; the result of a run is `pass`, `warn`, `fail`, `unknown` (could not inspect, never a pass) or `skip` (does not apply). See [the threat model](../threat-model.md) for what stackward reads and why there is no score.\n\n")
	fmt.Fprintf(&b, "%d checks in the catalog.\n", len(entries))
	group := ""
	for _, e := range entries {
		if e.Group != group {
			group = e.Group
			fmt.Fprintf(&b, "\n## %s (%s)\n\n| Id | Severity | Check |\n|---|---|---|\n", catalog.GroupName(group), group)
		}
		fmt.Fprintf(&b, "| [%s](%s.md) | %s | %s |\n", e.ID, e.ID, e.Severity, cell(e.Title))
	}
	return b.String()
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ")
}
